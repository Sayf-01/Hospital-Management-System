-- Hospital Management System - Phase 2 schema (schema v2, PostgreSQL)
-- SOEN 363
--
-- Builds on the Phase 1 schema. It holds the integrated data from four
-- source hospitals (A, B, C, D) without ID clashes, and every row can be
-- traced back to its source record.
--
-- WARNING: this file starts by dropping every table, so it erases all data.
-- The pipeline reruns it before each import.
--
-- What changed from Phase 1 (details in phase2/docs/schema_changes.md):
--   * source_systems: one row per source hospital.
--   * Every data table except patients and icd9_dictionary has
--     source_code + source_local_id, unique together.
--   * Patients can be merged across sources, so they get patient_source_map
--     instead (one integrated patient, one or more source records).
--   * patient_match_candidates: uncertain matches, kept as separate patients.
--   * quarantine_records: records rejected during cleaning, checking or
--     integration, so they can be counted and shown in SQL.
--   * Every TIMESTAMP is now TIMESTAMPTZ (all times are UTC instants).
--     date_of_birth stays DATE.
--
-- Phase 1 conventions still apply:
--   * "ICU or CCU" (Q5, Q7, Q8, Q10, Q13): unit_type IN ('ICU', 'CCU')
--   * "critical care" (Q9, Q16): unit_type IN ('MICU', 'SICU', 'ICU', 'CCU')
--   * Q7 "entered through the Emergency Department": admission_source = 'Emergency Department'
--   * Q19 "died during the stay": admission_status = 'Deceased'
--   * Q18: newest note_datetime; ties broken by highest note_id
--   * A radiology examination reaches its admission through its diagnostic order
--   * Every completed admission is expected to have one Primary diagnosis; the
--     index below only prevents more than one, so it is checked after import


-- Calendar-day queries (such as Q20) cast TIMESTAMPTZ values to DATE, and that
-- cast uses the session time zone. Pin this database to UTC so every client
-- (psql, pgAdmin, Python) sees the same dates.
DO $$
BEGIN
    EXECUTE format('ALTER DATABASE %I SET timezone TO %L', current_database(), 'UTC');
END
$$;
SET timezone TO 'UTC';


-- Drop everything first (view, then tables in reverse creation order)
DROP VIEW  IF EXISTS radiology_exam_details;
DROP TABLE IF EXISTS quarantine_records;
DROP TABLE IF EXISTS patient_match_candidates;
DROP TABLE IF EXISTS patient_source_map;
DROP TABLE IF EXISTS discharge_records;
DROP TABLE IF EXISTS diagnoses;
DROP TABLE IF EXISTS unit_stays;
DROP TABLE IF EXISTS surgical_procedures;
DROP TABLE IF EXISTS radiology_reports;
DROP TABLE IF EXISTS radiology_examinations;
DROP TABLE IF EXISTS diagnostic_examinations;
DROP TABLE IF EXISTS diagnostic_orders;
DROP TABLE IF EXISTS clinical_notes;
DROP TABLE IF EXISTS triage_assessments;
DROP TABLE IF EXISTS admissions;
DROP TABLE IF EXISTS hospital_units;
DROP TABLE IF EXISTS icd9_dictionary;
DROP TABLE IF EXISTS healthcare_professionals;
DROP TABLE IF EXISTS patients;
DROP TABLE IF EXISTS source_systems;


-- NEW: one row per source hospital
CREATE TABLE source_systems (
    source_code    CHAR(1)      PRIMARY KEY
                   CHECK (source_code IN ('A', 'B', 'C', 'D')),
    hospital_name  VARCHAR(100) NOT NULL,
    continent      VARCHAR(30)  NOT NULL,
    file_format    VARCHAR(20)  NOT NULL,   -- TXT, CSV, XML, JSON
    time_zone      VARCHAR(50)  NOT NULL    -- IANA name, e.g. 'America/Toronto'
);

-- No source columns here: a patient can come from several sources,
-- so the links live in patient_source_map
CREATE TABLE patients (
    patient_id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name               VARCHAR(50)  NOT NULL,
    last_name                VARCHAR(50)  NOT NULL,
    date_of_birth            DATE         NOT NULL,
    gender                   VARCHAR(20)  NOT NULL,
    -- cleaning prefixes each source's numbers (P2-A-..., P2-B-...), so numbers
    -- from different hospitals cannot collide here
    health_insurance_number  VARCHAR(30)  UNIQUE,
    address                  VARCHAR(255),
    phone_number             VARCHAR(20),
    emergency_contact_info   VARCHAR(255),
    life_status              VARCHAR(20)  NOT NULL DEFAULT 'Alive'
                             CHECK (life_status IN ('Alive', 'Deceased')),
    date_of_death            TIMESTAMPTZ,
    -- a patient is Deceased exactly when a date of death is recorded
    CHECK ((life_status = 'Deceased') = (date_of_death IS NOT NULL))
);

CREATE TABLE healthcare_professionals (
    professional_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code      CHAR(1)      NOT NULL REFERENCES source_systems (source_code),
    source_local_id  VARCHAR(50)  NOT NULL,
    first_name       VARCHAR(50)  NOT NULL,
    last_name        VARCHAR(50)  NOT NULL,
    role             VARCHAR(50)  NOT NULL
                     CHECK (role IN ('Physician', 'Surgeon', 'Nurse', 'Radiologist', 'Technician')),
    specialty        VARCHAR(100),
    UNIQUE (source_code, source_local_id)
);

-- Shared by all four sources: they use the same real ICD-9 codes,
-- so the four dictionaries combine into one set
CREATE TABLE icd9_dictionary (
    icd9_code         VARCHAR(10)  PRIMARY KEY,   -- e.g. '410.9'
    official_title    VARCHAR(255) NOT NULL,
    description       TEXT,
    disease_category  VARCHAR(100)
);

CREATE TABLE hospital_units (
    unit_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code      CHAR(1)      NOT NULL REFERENCES source_systems (source_code),
    source_local_id  VARCHAR(50)  NOT NULL,
    unit_name        VARCHAR(100) NOT NULL,
    unit_type        VARCHAR(50)  NOT NULL
                     CHECK (unit_type IN ('Emergency', 'General Ward', 'MICU', 'SICU', 'ICU', 'CCU', 'Other')),
    UNIQUE (source_code, source_local_id)
);

CREATE TABLE admissions (
    admission_id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code                CHAR(1)     NOT NULL REFERENCES source_systems (source_code),
    source_local_id            VARCHAR(50) NOT NULL,
    patient_id                 INT NOT NULL REFERENCES patients (patient_id),
    admitting_professional_id  INT REFERENCES healthcare_professionals (professional_id),
    admission_datetime         TIMESTAMPTZ NOT NULL,
    discharge_datetime         TIMESTAMPTZ,              -- empty until discharge
    admission_type             VARCHAR(50) NOT NULL
                               CHECK (admission_type IN ('Emergency', 'Urgent', 'Elective', 'Outpatient', 'Newborn')),
    admission_source           VARCHAR(50)
                               CHECK (admission_source IS NULL OR admission_source IN
                                      ('Emergency Department', 'Referral',
                                       'Transfer from Another Hospital', 'Walk-in', 'Other')),
    reason_for_admission       TEXT,
    current_condition          VARCHAR(255),
    insurance_info             VARCHAR(100),
    admission_status           VARCHAR(20) NOT NULL
                               CHECK (admission_status IN ('Admitted', 'Discharged', 'Deceased')),
    CHECK (discharge_datetime IS NULL OR discharge_datetime > admission_datetime),
    CHECK ((admission_status = 'Admitted' AND discharge_datetime IS NULL)
        OR (admission_status IN ('Discharged', 'Deceased') AND discharge_datetime IS NOT NULL)),
    UNIQUE (source_code, source_local_id),
    -- lets other tables check that their patient_id matches the admission
    UNIQUE (admission_id, patient_id)
);

CREATE TABLE triage_assessments (
    triage_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code          CHAR(1)     NOT NULL REFERENCES source_systems (source_code),
    source_local_id      VARCHAR(50) NOT NULL,
    admission_id         INT NOT NULL REFERENCES admissions (admission_id),
    nurse_id             INT REFERENCES healthcare_professionals (professional_id),
    assessment_datetime  TIMESTAMPTZ NOT NULL,
    priority_level       VARCHAR(30) NOT NULL
                         CHECK (priority_level IN ('High-Priority Emergency', 'Urgent', 'Non-Urgent')),
    blood_pressure       VARCHAR(15),
    heart_rate           INT,
    respiratory_rate     INT,
    body_temperature     DECIMAL(4,1),   -- degrees Celsius
    oxygen_saturation    DECIMAL(4,1),
    pain_level           INT CHECK (pain_level BETWEEN 0 AND 10),
    reported_symptoms    TEXT,
    known_allergies      TEXT,
    current_medications  TEXT,
    UNIQUE (source_code, source_local_id)
);

CREATE TABLE clinical_notes (
    note_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code      CHAR(1)     NOT NULL REFERENCES source_systems (source_code),
    source_local_id  VARCHAR(50) NOT NULL,
    admission_id     INT NOT NULL REFERENCES admissions (admission_id),
    author_id        INT NOT NULL REFERENCES healthcare_professionals (professional_id),
    note_type        VARCHAR(50) NOT NULL
                     CHECK (note_type IN ('Initial Assessment', 'Progress Note', 'Discharge Summary')),
    note_datetime    TIMESTAMPTZ NOT NULL,
    note_contents    TEXT        NOT NULL,
    UNIQUE (source_code, source_local_id)
);

CREATE TABLE diagnostic_orders (
    order_id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code            CHAR(1)      NOT NULL REFERENCES source_systems (source_code),
    source_local_id        VARCHAR(50)  NOT NULL,
    patient_id             INT NOT NULL,
    admission_id           INT NOT NULL,
    ordering_physician_id  INT NOT NULL REFERENCES healthcare_professionals (professional_id),
    order_datetime         TIMESTAMPTZ  NOT NULL,
    requested_examination  VARCHAR(100) NOT NULL,
    clinical_reason        TEXT,
    priority               VARCHAR(20),   -- STAT, Routine
    order_status           VARCHAR(20),   -- Ordered, Completed, Cancelled
    UNIQUE (source_code, source_local_id),
    -- the patient must be the one who owns the admission
    FOREIGN KEY (admission_id, patient_id) REFERENCES admissions (admission_id, patient_id)
);

-- One order can lead to any number of examinations (blood test, ECG, X-ray, ...)
CREATE TABLE diagnostic_examinations (
    examination_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code           CHAR(1)      NOT NULL REFERENCES source_systems (source_code),
    source_local_id       VARCHAR(50)  NOT NULL,
    order_id              INT NOT NULL REFERENCES diagnostic_orders (order_id),
    performed_by_id       INT REFERENCES healthcare_professionals (professional_id),
    examination_type      VARCHAR(100) NOT NULL,
    examination_datetime  TIMESTAMPTZ  NOT NULL,
    examination_status    VARCHAR(20),
    result_summary        TEXT,
    UNIQUE (source_code, source_local_id)
);

-- Imaging details for an examination (at most one per examination)
CREATE TABLE radiology_examinations (
    radiology_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code             CHAR(1)     NOT NULL REFERENCES source_systems (source_code),
    source_local_id         VARCHAR(50) NOT NULL,
    examination_id          INT NOT NULL UNIQUE REFERENCES diagnostic_examinations (examination_id),
    referring_physician_id  INT REFERENCES healthcare_professionals (professional_id),
    technician_id           INT REFERENCES healthcare_professionals (professional_id),
    body_area               VARCHAR(50),
    image_link              VARCHAR(255),
    UNIQUE (source_code, source_local_id)
);

-- At most one report per radiology examination
CREATE TABLE radiology_reports (
    report_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code      CHAR(1)     NOT NULL REFERENCES source_systems (source_code),
    source_local_id  VARCHAR(50) NOT NULL,
    radiology_id     INT NOT NULL UNIQUE REFERENCES radiology_examinations (radiology_id),
    radiologist_id   INT NOT NULL REFERENCES healthcare_professionals (professional_id),
    report_datetime  TIMESTAMPTZ NOT NULL,
    findings         TEXT,
    impression       TEXT,
    UNIQUE (source_code, source_local_id)
);

CREATE TABLE surgical_procedures (
    procedure_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code         CHAR(1)      NOT NULL REFERENCES source_systems (source_code),
    source_local_id     VARCHAR(50)  NOT NULL,
    admission_id        INT NOT NULL REFERENCES admissions (admission_id),
    surgeon_id          INT NOT NULL REFERENCES healthcare_professionals (professional_id),
    procedure_name      VARCHAR(150) NOT NULL,
    procedure_datetime  TIMESTAMPTZ  NOT NULL,
    operating_room      VARCHAR(20),
    procedure_notes     TEXT,
    UNIQUE (source_code, source_local_id)
);

-- The unit type is not repeated here; join hospital_units to get it
CREATE TABLE unit_stays (
    unit_stay_id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code               CHAR(1)     NOT NULL REFERENCES source_systems (source_code),
    source_local_id           VARCHAR(50) NOT NULL,
    admission_id              INT NOT NULL REFERENCES admissions (admission_id),
    unit_id                   INT NOT NULL REFERENCES hospital_units (unit_id),
    responsible_physician_id  INT REFERENCES healthcare_professionals (professional_id),
    ward_and_room             VARCHAR(50),
    bed_number                VARCHAR(20),
    entry_datetime            TIMESTAMPTZ NOT NULL,
    exit_datetime             TIMESTAMPTZ,          -- empty while still in the unit
    reason_for_transfer       TEXT,
    CHECK (exit_datetime IS NULL OR exit_datetime > entry_datetime),
    UNIQUE (source_code, source_local_id)
);

CREATE TABLE diagnoses (
    diagnosis_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code              CHAR(1)     NOT NULL REFERENCES source_systems (source_code),
    source_local_id          VARCHAR(50) NOT NULL,
    patient_id               INT NOT NULL,
    admission_id             INT NOT NULL,
    icd9_code                VARCHAR(10) NOT NULL REFERENCES icd9_dictionary (icd9_code),
    diagnosing_physician_id  INT REFERENCES healthcare_professionals (professional_id),
    diagnosis_datetime       TIMESTAMPTZ NOT NULL,
    diagnosis_type           VARCHAR(20) NOT NULL
                             CHECK (diagnosis_type IN ('Primary', 'Secondary', 'Preliminary')),
    UNIQUE (source_code, source_local_id),
    -- same code twice in one admission only if the type differs
    UNIQUE (admission_id, icd9_code, diagnosis_type),
    -- the patient must be the one who owns the admission
    FOREIGN KEY (admission_id, patient_id) REFERENCES admissions (admission_id, patient_id)
);

-- At most one primary diagnosis per admission
CREATE UNIQUE INDEX one_primary_per_admission
    ON diagnoses (admission_id) WHERE diagnosis_type = 'Primary';

-- At most one discharge record per admission
CREATE TABLE discharge_records (
    discharge_id                    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code                     CHAR(1)     NOT NULL REFERENCES source_systems (source_code),
    source_local_id                 VARCHAR(50) NOT NULL,
    admission_id                    INT NOT NULL UNIQUE REFERENCES admissions (admission_id),
    responsible_physician_id        INT REFERENCES healthcare_professionals (professional_id),
    discharge_destination           VARCHAR(100),
    discharge_condition             VARCHAR(20)
                                    CHECK (discharge_condition IN
                                           ('Improved', 'Stable', 'Unchanged', 'Deteriorated', 'Deceased')),
    prescribed_medications          TEXT,
    follow_up_instructions          TEXT,
    follow_up_appointment_datetime  TIMESTAMPTZ,
    UNIQUE (source_code, source_local_id)
);


-- NEW: links each source patient record to its integrated patient.
-- One integrated patient can have several source records (an M1 merge),
-- but each source record belongs to exactly one integrated patient.
CREATE TABLE patient_source_map (
    source_code              CHAR(1)     NOT NULL REFERENCES source_systems (source_code),
    source_local_id          VARCHAR(50) NOT NULL,
    patient_id               INT         NOT NULL REFERENCES patients (patient_id),
    match_rule               VARCHAR(10) NOT NULL
                             CHECK (match_rule IN ('NEW', 'M1')),   -- NEW = not merged; M1 = merged
    source_insurance_number  VARCHAR(30),   -- the number exactly as this source sent it (after cleaning)
    PRIMARY KEY (source_code, source_local_id)
);

-- NEW: possible matches that were NOT merged (rule U1), kept for review
CREATE TABLE patient_match_candidates (
    candidate_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id_1  INT          NOT NULL REFERENCES patients (patient_id),
    patient_id_2  INT          NOT NULL REFERENCES patients (patient_id),
    match_rule    VARCHAR(10)  NOT NULL CHECK (match_rule IN ('U1', 'U2')),
    reason        TEXT         NOT NULL,
    decision      VARCHAR(20)  NOT NULL DEFAULT 'Not merged'
                  CHECK (decision IN ('Not merged', 'Merged', 'Rejected')),
    -- store each pair once, smaller ID first
    CHECK (patient_id_1 < patient_id_2),
    UNIQUE (patient_id_1, patient_id_2)
);

-- NEW: records rejected at any stage, so they can be counted and shown in SQL.
-- Separate from the main tables, so raw files are never stored as text there.
CREATE TABLE quarantine_records (
    quarantine_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage            VARCHAR(20)  NOT NULL
                     CHECK (stage IN ('load', 'clean', 'relationships', 'chronology', 'integrate')),
    source_code      CHAR(1)      NOT NULL REFERENCES source_systems (source_code),
    entity           VARCHAR(50)  NOT NULL,   -- target table name, e.g. 'admissions'
    source_local_id  VARCHAR(50),             -- empty when a malformed row has no readable ID
    source_line      VARCHAR(100),            -- A/B: line number; C/D: position in the XML/JSON tree
    reason           TEXT         NOT NULL,
    raw_record       TEXT
);


-- Radiology examinations with their patient, admission and source attached,
-- so the radiology queries don't repeat the long join
CREATE VIEW radiology_exam_details AS
SELECT  r.radiology_id,
        r.examination_id,
        r.source_code,
        o.patient_id,
        o.admission_id,
        e.examination_type,
        e.examination_datetime,
        e.examination_status,
        r.body_area,
        r.referring_physician_id,
        r.technician_id
FROM    radiology_examinations r
JOIN    diagnostic_examinations e ON e.examination_id = r.examination_id
JOIN    diagnostic_orders       o ON o.order_id       = e.order_id;
